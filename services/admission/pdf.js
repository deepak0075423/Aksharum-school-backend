'use strict';
/**
 * The admission module's printable documents, drawn with pdfkit:
 *
 *   acknowledgement  what was submitted, and when — for the family's records
 *   admitCard        the exam's admit card, with the student's photo when one
 *                    was uploaded and a QR the door staff can scan
 *   scorecard        a published exam result
 *   offerLetter      the seat offered, the deadlines, the fee
 *   selectionList    a published (or draft, for the office) list, as printed
 *                    for the notice board
 *   application      the full application as the office sees it
 *
 * A builder streams to `res` and never reads the database — the caller
 * gathers exactly what the reader is allowed to see. Receipts are not here:
 * they use the school's own receipt designs (services/receiptRenderer).
 */
const PDFDocument = require('pdfkit');
const QRCode = require('qrcode');
const { schoolLogoPath } = require('../../utils/schoolLogoFile');
const fmt = require('./format');

const C = { band: '#312E81', ink: '#1E293B', muted: '#64748B', line: '#E2E8F0', head: '#F1F5F9', accent: '#4F46E5', green: '#15803D', red: '#B91C1C' };
// pdfkit's standard fonts are WinAnsi: anything outside it prints as garbage.
const safe = (v) => String(v ?? '').replace(/[₹]/g, 'Rs. ').replace(/[–—]/g, '-').replace(/[‘’]/g, "'").replace(/[“”]/g, '"').replace(/[^\x20-\x7E\xA0-\xFF\n]/g, '');

function start(res, { school, title, subtitle = '', filename, theme = null, inline = false }) {
    const doc = new PDFDocument({ size: 'A4', margin: 40, bufferPages: true, info: { Title: safe(title) } });
    res.setHeader('Content-Type', 'application/pdf');
    res.setHeader('Content-Disposition', `${inline ? 'inline' : 'attachment'}; filename="${filename.replace(/[^\w.-]+/g, '_')}"`);
    res.setHeader('Cache-Control', 'private, no-store');
    const done = new Promise((resolve, reject) => { res.on('finish', resolve); res.on('close', resolve); doc.on('error', reject); });
    doc.pipe(res);
    const X = 40; const W = doc.page.width - 80;
    const band = /^#[0-9a-f]{6}$/i.test(theme || '') ? theme : C.band;
    doc.rect(X, 36, W, 62).fill(band);
    const logo = schoolLogoPath(school);
    if (logo) { try { doc.image(logo, X + 10, 43, { fit: [48, 48] }); } catch { /* unreadable logo */ } }
    doc.font('Helvetica-Bold').fontSize(15).fillColor('#fff').text(safe(school?.name || 'School'), X + 64, 48, { width: W - 128, align: 'center' });
    doc.font('Helvetica').fontSize(10).fillColor('#E0E7FF').text(safe(title), X + 64, 70, { width: W - 128, align: 'center' });
    doc.y = 110;
    if (subtitle) { doc.font('Helvetica').fontSize(9).fillColor(C.muted).text(safe(subtitle), X, doc.y, { width: W, align: 'center' }); doc.moveDown(0.4); }
    return { doc, X, W, done };
}

function finish(doc, footer = 'Generated by the school\'s admission portal.') {
    const range = doc.bufferedPageRange();
    for (let i = range.start; i < range.start + range.count; i += 1) {
        doc.switchToPage(i);
        const y = doc.page.height - 30;
        doc.font('Helvetica').fontSize(7.5).fillColor(C.muted)
            .text(safe(footer), 40, y, { width: doc.page.width - 190, lineBreak: false })
            .text(`Page ${i + 1} of ${range.count}`, doc.page.width - 150, y, { width: 110, align: 'right', lineBreak: false });
    }
    doc.end();
}

function heading(ctx, text) {
    const { doc, X, W } = ctx;
    if (doc.y > doc.page.height - 120) doc.addPage();
    doc.moveDown(0.5);
    doc.rect(X, doc.y, W, 18).fill(C.head);
    doc.font('Helvetica-Bold').fontSize(9.5).fillColor(C.ink).text(safe(text).toUpperCase(), X + 6, doc.y + 5, { width: W - 12, characterSpacing: 0.5 });
    doc.moveDown(0.7);
}

function pairs(ctx, items, { cols = 2 } = {}) {
    const { doc, X, W } = ctx;
    const list = items.filter(([, v]) => v !== undefined && v !== null && v !== '');
    const col = (W - 12) / cols;
    for (let i = 0; i < list.length; i += cols) {
        if (doc.y > doc.page.height - 80) doc.addPage();
        const y = doc.y;
        let maxH = 0;
        for (let j = 0; j < cols; j += 1) {
            const p = list[i + j];
            if (!p) continue;
            const x = X + 6 + j * col;
            doc.font('Helvetica').fontSize(7.5).fillColor(C.muted).text(safe(p[0]).toUpperCase(), x, y, { width: col - 10 });
            doc.font('Helvetica-Bold').fontSize(10).fillColor(C.ink).text(safe(p[1]), x, y + 10, { width: col - 10 });
            maxH = Math.max(maxH, doc.y - y);
        }
        doc.y = y + maxH + 6;
    }
}

function para(ctx, text, { size = 10, color = C.ink, bold = false } = {}) {
    const { doc, X, W } = ctx;
    if (doc.y > doc.page.height - 90) doc.addPage();
    doc.font(bold ? 'Helvetica-Bold' : 'Helvetica').fontSize(size).fillColor(color).text(safe(text), X + 6, doc.y, { width: W - 12, lineGap: 2 });
    doc.moveDown(0.4);
}

function table(ctx, headers, rows, widths) {
    const { doc, X, W } = ctx;
    const ws = widths.map((w) => w * (W / widths.reduce((s, x) => s + x, 0)));
    const drawHead = () => {
        const y = doc.y;
        doc.rect(X, y, W, 18).fill(C.head);
        let x = X;
        headers.forEach((h, i) => { doc.font('Helvetica-Bold').fontSize(8.5).fillColor(C.ink).text(safe(h), x + 4, y + 5, { width: ws[i] - 8, lineBreak: false }); x += ws[i]; });
        doc.y = y + 20;
    };
    drawHead();
    for (const r of rows) {
        if (doc.y > doc.page.height - 70) { doc.addPage(); drawHead(); }
        const y = doc.y;
        let x = X;
        let h = 0;
        r.forEach((cell, i) => {
            doc.font('Helvetica').fontSize(9).fillColor(C.ink).text(safe(cell), x + 4, y + 3, { width: ws[i] - 8 });
            h = Math.max(h, doc.y - y);
            x += ws[i];
        });
        doc.y = y + Math.max(16, h + 4);
        doc.moveTo(X, doc.y - 1).lineTo(X + W, doc.y - 1).lineWidth(0.5).strokeColor(C.line).stroke();
    }
}

// ── Documents ────────────────────────────────────────────────────────────────

async function acknowledgement(res, { school, theme, app, className, yearName, roundName, applicantName, answers, documents }) {
    const ctx = start(res, { school, theme, title: 'Application acknowledgement', subtitle: `${roundName} · ${yearName}`, filename: `acknowledgement-${app.applicationNumber}.pdf` });
    heading(ctx, 'Application');
    pairs(ctx, [
        ['Application number', app.applicationNumber], ['Submitted on', fmt.fmtDateTime(app.submittedAt)],
        ['Student', app.studentName], ['Class applied for', className],
        ['Applicant', applicantName], ['Current status', app.statusLabel],
    ]);
    for (const sec of answers || []) {
        heading(ctx, sec.title);
        pairs(ctx, sec.fields.map((f) => [f.label, f.hidden ? '(restricted)' : String(f.value ?? '')]));
    }
    if (documents?.length) {
        heading(ctx, 'Documents uploaded');
        table(ctx, ['Document', 'File', 'Status'], documents.map((d) => [d.name, d.originalName || '', d.status]), [3, 3, 2]);
    }
    ctx.doc.moveDown(1);
    para(ctx, 'Keep this acknowledgement for your records. Quote the application number in every message to the school.', { size: 9, color: C.muted });
    finish(ctx.doc);
    return ctx.done;
}

async function admitCard(res, { school, theme, app, exam, candidate, className, photo, venueText }) {
    const ctx = start(res, { school, theme, title: exam.mode === 'interview' ? 'Interview call letter' : 'Admit card', subtitle: exam.name, filename: `admit-card-${candidate.rollNumber}.pdf` });
    const { doc, X, W } = ctx;
    const top = doc.y + 4;
    // Photo box on the right.
    const pw = 96; const ph = 118;
    doc.rect(X + W - pw - 6, top, pw, ph).lineWidth(1).strokeColor(C.line).stroke();
    if (photo) {
        try { doc.image(photo, X + W - pw - 4, top + 2, { fit: [pw - 4, ph - 4], align: 'center', valign: 'center' }); } catch { /* not an image pdfkit reads */ }
    } else {
        doc.font('Helvetica').fontSize(8).fillColor(C.muted).text('Paste a recent photo here', X + W - pw - 2, top + 50, { width: pw - 8, align: 'center' });
    }
    doc.y = top;
    const save = ctx.W;
    ctx.W = W - pw - 20;
    pairs(ctx, [
        ['Roll number', candidate.rollNumber], ['Application number', app.applicationNumber],
        ['Candidate', app.studentName], ['Class', className],
        ['Date', fmt.fmtDate(candidate.slot || exam.startsAt, { weekday: true })], ['Time', fmt.fmtTime(candidate.slot || exam.startsAt)],
        ['Reporting time', exam.reportingTime ? fmt.fmtClock(exam.reportingTime) : ''], ['Room', candidate.room || exam.venue?.room || ''],
    ]);
    ctx.W = save;
    doc.y = Math.max(doc.y, top + ph + 10);
    heading(ctx, 'Venue');
    para(ctx, venueText || 'At the school');
    if (exam.subjects?.length && exam.mode !== 'interview') {
        heading(ctx, 'Subjects');
        table(ctx, ['Subject', 'Maximum marks'], exam.subjects.map((s) => [s.name, String(s.maxMarks)]), [4, 2]);
    }
    if (exam.requiredItems) { heading(ctx, 'Bring with you'); para(ctx, exam.requiredItems); }
    const instructions = [exam.admitCard?.instructions, exam.instructions].filter(Boolean).join('\n\n');
    if (instructions) { heading(ctx, 'Instructions'); para(ctx, instructions, { size: 9.5 }); }
    try {
        const qr = await QRCode.toBuffer(`ADMIT|${candidate.rollNumber}|${app.applicationNumber}`, { margin: 1, width: 180 });
        if (doc.y > doc.page.height - 190) doc.addPage();
        doc.moveDown(0.6);
        const y = doc.y;
        doc.image(qr, X + 6, y, { width: 84 });
        doc.font('Helvetica').fontSize(8.5).fillColor(C.muted).text('Show this card at the entrance. The QR carries the roll and application numbers so staff can check them quickly.', X + 100, y + 18, { width: W - 120 });
        doc.y = y + 90;
    } catch { /* QR is a convenience */ }
    doc.moveDown(1.5);
    doc.font('Helvetica').fontSize(9).fillColor(C.ink).text('Signature of the candidate', X + 6, doc.y, { width: 200 });
    doc.text('Authorised signatory', X + W - 200, doc.y - 11, { width: 194, align: 'right' });
    finish(ctx.doc);
    return ctx.done;
}

async function scorecard(res, { school, theme, app, className, result }) {
    const ctx = start(res, { school, theme, title: 'Scorecard', subtitle: result.exam, filename: `scorecard-${app.applicationNumber}.pdf` });
    pairs(ctx, [
        ['Candidate', app.studentName], ['Application number', app.applicationNumber], ['Class', className],
        ['Published on', fmt.fmtDate(result.publishedAt)],
    ]);
    heading(ctx, 'Result');
    if (result.absent) para(ctx, 'Absent', { bold: true, color: C.red });
    else {
        if (result.subjects?.length) table(ctx, ['Subject', 'Marks', 'Out of'], result.subjects.map((s) => [s.name, s.marks == null ? '-' : String(s.marks), String(s.maxMarks)]), [4, 2, 2]);
        ctx.doc.moveDown(0.5);
        pairs(ctx, [
            ['Total', result.total == null ? '-' : `${result.total} / ${result.maxMarks}`],
            ['Percentage', result.percentage == null ? '-' : `${result.percentage}%`],
            ['Grade', result.grade || ''],
            ['Result', result.passed ? 'Qualified' : 'Not qualified'],
        ]);
    }
    finish(ctx.doc);
    return ctx.done;
}

async function offerLetter(res, { school, theme, app, className, yearName, offer, applicantName }) {
    const ctx = start(res, { school, theme, title: 'Offer of admission', subtitle: offer.offerNumber, filename: `offer-${offer.offerNumber}.pdf` });
    para(ctx, fmt.fmtDate(offer.issuedAt), { color: C.muted, size: 9 });
    para(ctx, `Dear ${applicantName || 'Parent'},`);
    para(ctx, `We are pleased to offer ${app.studentName} admission to ${className} for the academic year ${yearName} (application ${app.applicationNumber}).`);
    heading(ctx, 'What happens next');
    pairs(ctx, [
        ['Offer number', offer.offerNumber], ['Status', offer.status],
        ['Accept by', fmt.fmtDateTime(offer.respondBy)], ['Admission fee', fmt.moneyPlain(offer.feeAmount)],
        ['Pay the fee by', fmt.fmtDate(offer.feeDueAt)],
    ]);
    para(ctx, 'Accept the offer and pay the admission fee from your admission dashboard. The seat is held until the dates above; an offer that is not taken up by then lapses and the seat is offered to the next applicant.', { size: 9.5 });
    ctx.doc.moveDown(2);
    para(ctx, 'Admission Office', { bold: true });
    para(ctx, school?.name || '', { color: C.muted });
    finish(ctx.doc);
    return ctx.done;
}

async function selectionList(res, { school, theme, list, className, roundName, lines, office = false }) {
    const ctx = start(res, { school, theme, title: `${list.name} — ${className}`, subtitle: `${roundName}${list.publishedAt ? ` · published ${fmt.fmtDate(list.publishedAt)}` : ' · DRAFT'}`, filename: `${list.name}-${className}.pdf` });
    const vis = list.visibility || {};
    const selected = lines.filter((l) => l.decision === 'selected');
    const waiting = lines.filter((l) => l.decision === 'waitlisted');
    const head = ['#', 'Application', ...(office || vis.showNames ? ['Name'] : []), ...(office || vis.showScore ? ['Score'] : []), ...(office ? ['Decision'] : [])];
    const row = (l, i) => [String(office || vis.showRank ? l.rank : i + 1), l.applicationNumber, ...(office || vis.showNames ? [l.studentName] : []), ...(office || vis.showScore ? [l.score == null ? '-' : String(l.score)] : []), ...(office ? [l.decision.replace('_', ' ')] : [])];
    const widths = [1, 3, ...(office || vis.showNames ? [4] : []), ...(office || vis.showScore ? [1.5] : []), ...(office ? [2] : [])];
    heading(ctx, `Selected (${selected.length})`);
    if (selected.length) table(ctx, head, selected.map(row), widths); else para(ctx, 'Nobody', { color: C.muted });
    heading(ctx, `Waiting list (${waiting.length})`);
    if (waiting.length) table(ctx, head, waiting.map((l, i) => row({ ...l, rank: l.waitPosition || i + 1 }, i)), widths); else para(ctx, 'Nobody', { color: C.muted });
    if (office) {
        const rest = lines.filter((l) => !['selected', 'waitlisted'].includes(l.decision));
        if (rest.length) { heading(ctx, `Not on this list (${rest.length})`); table(ctx, head, rest.map(row), widths); }
    }
    finish(ctx.doc, office ? 'Office copy — includes names and scores.' : 'Published by the school\'s admission office.');
    return ctx.done;
}

async function applicationPdf(res, { school, theme, app, className, yearName, roundName, applicantName, answers, documents, payments }) {
    const ctx = start(res, { school, theme, title: `Application ${app.applicationNumber || '(draft)'}`, subtitle: `${roundName} · ${yearName}`, filename: `application-${app.applicationNumber || app._id}.pdf` });
    pairs(ctx, [
        ['Student', app.studentName], ['Class', className], ['Applicant', applicantName], ['Status', app.statusLabel],
        ['Submitted', fmt.fmtDateTime(app.submittedAt)], ['Contact', [app.guardianName, app.guardianPhone, app.guardianEmail].filter(Boolean).join(' · ')],
    ]);
    for (const sec of answers || []) {
        heading(ctx, sec.title);
        pairs(ctx, sec.fields.map((f) => [f.label, f.hidden ? '(restricted)' : String(f.value ?? '')]));
    }
    if (documents?.length) { heading(ctx, 'Documents'); table(ctx, ['Document', 'Status', 'Reviewed'], documents.map((d) => [d.name, d.status, d.reviewedAt ? fmt.fmtDate(d.reviewedAt) : '']), [4, 2, 2]); }
    if (payments?.length) { heading(ctx, 'Payments'); table(ctx, ['Receipt', 'For', 'Amount', 'Mode', 'Date'], payments.map((p) => [p.receiptNumber || '', p.kind.replace('_', ' '), fmt.moneyPlain(p.amount), p.mode, fmt.fmtDate(p.paidAt)]), [2.5, 2.5, 2, 1.5, 2]); }
    finish(ctx.doc, 'Office copy — confidential.');
    return ctx.done;
}

module.exports = { acknowledgement, admitCard, scorecard, offerLetter, selectionList, applicationPdf, safe };
